#!/usr/bin/env python3
"""Record an animated GIF walkthrough of the UI for the README.

Drives a headless browser through a real research flow against a running app,
grabbing frames, then assembles them into a looping GIF.

No API key is used or needed: the walkthrough stays on the free retrieval path,
so the GIF can be regenerated by anyone who clones the repo.

    streamlit run app/streamlit_app.py --server.port 8795
    python scripts/capture_demo_gif.py
"""

from __future__ import annotations

import argparse
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "docs", "images", "demo.gif")

QUESTION = "Who is treated as a beneficial owner of a legal entity customer?"


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--url", default="http://127.0.0.1:8795")
    parser.add_argument("--out", default=OUT)
    parser.add_argument("--width", type=int, default=1280)
    parser.add_argument("--height", type=int, default=800)
    parser.add_argument("--scale", type=float, default=0.62,
                        help="downscale factor to keep the GIF small enough for a README")
    args = parser.parse_args(argv)

    try:
        from playwright.sync_api import sync_playwright
    except ImportError:
        print("pip install playwright && python -m playwright install chromium")
        return 1
    from PIL import Image

    tmpdir = os.path.join(ROOT, "docs", "images", "_frames")
    os.makedirs(tmpdir, exist_ok=True)
    os.makedirs(os.path.dirname(args.out), exist_ok=True)

    frames: list[tuple[str, int]] = []   # (path, duration_ms)

    def shot(name: str, hold_ms: int) -> None:
        path = os.path.join(tmpdir, f"{len(frames):03d}-{name}.png")
        page.screenshot(path=path)
        frames.append((path, hold_ms))

    with sync_playwright() as pw:
        browser = pw.chromium.launch()
        page = browser.new_page(viewport={"width": args.width, "height": args.height})
        page.goto(args.url, wait_until="networkidle", timeout=60_000)
        page.wait_for_selector("text=Ask a regulatory question", timeout=60_000)
        page.wait_for_timeout(2000)

        shot("start", 1800)

        # Type the question a few characters at a time so the GIF reads as use.
        box = page.locator("textarea").first
        box.click()
        chunks = [QUESTION[i:i + 14] for i in range(0, len(QUESTION), 14)]
        typed = ""
        for part in chunks:
            typed += part
            box.fill(typed)
            page.wait_for_timeout(120)
            shot("typing", 260)

        shot("typed", 1200)

        page.click("text=Retrieve passages only")
        page.wait_for_selector("text=passage(s)", timeout=60_000)
        page.wait_for_timeout(1800)
        shot("results", 2600)

        # Scroll through the evidence.
        for _ in range(4):
            page.mouse.wheel(0, 420)
            page.wait_for_timeout(500)
            shot("scroll", 900)

        # Show the document library.
        page.mouse.wheel(0, -4000)
        page.wait_for_timeout(400)
        page.click("text=Document library")
        page.wait_for_timeout(2200)
        shot("library", 3000)

        browser.close()

    images = []
    durations = []
    for path, hold in frames:
        im = Image.open(path).convert("RGB")
        im = im.resize((int(im.width * args.scale), int(im.height * args.scale)),
                       Image.LANCZOS)
        images.append(im)
        durations.append(hold)

    images[0].save(
        args.out,
        save_all=True,
        append_images=images[1:],
        duration=durations,
        loop=0,
        optimize=True,
    )

    for path, _ in frames:
        os.remove(path)
    os.rmdir(tmpdir)

    size_mb = os.path.getsize(args.out) / (1024 * 1024)
    print(f"wrote {args.out}  ({len(images)} frames, {size_mb:.1f} MB)")
    if size_mb > 10:
        print("WARNING: over 10 MB — GitHub will be slow to render it. "
              "Lower --scale or drop frames.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
